function daysAgo(days: number, hours = 10): string {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(hours, 0, 0, 0);
  return d.toISOString();
}

function shift(
  id: string,
  jobId: string,
  date: string,
  startTime: string,
  endTime: string,
  headcount: number,
  checkinCode: string,
  status: Shift['status'] = 'open',
): Shift {
  return { id, jobId, date, startTime, endTime, headcount, checkinCode, status };
}

